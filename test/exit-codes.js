'use strict';

/**
 * 真机测试的**退出码词汇表**（唯一真相）。
 * ---------------------------------------------------------------------------
 * 为什么要有这张表：
 *   退出码是**自动 CI 唯一能看到的东西**。同一个码在不同脚本里
 *   表示两件事，CI 就读不出来 —— 比如 2 在 e2e 里是「检测到多编辑器实例」、
 *   在冒烟里是「有跳过、本轮没跑完」；3 在冒烟里是「有残留」、
 *   在 e2e 的异常处理里是「测试中断」。
 *
 *   ⇒ 所有真机脚本必须用**这张表**里的码。
 *   新增一种语义时，先在这里加，再在脚本里用 ——
 *   `test/exit-codes.test.js` 会守着「各脚本用的是不是这张表里的码」。
 */

/**
 * 0 = 全部通过
 * 1 = 有真失败（真回归）—— CI 必须红，这是要查的
 * 2 = 本轮没跑完（环境/引擎问题：编辑器没开、频道中毒、多实例）—— 可重试，**不是回归**
 * 3 = 有残留（文件留在用户工程里）—— 要人工清理
 * 4 = 测试自身中断（崩溃/未捕获异常）—— 脚本坏了，要看日志
 */
const EXIT = {
    OK: 0,
    FAILURE: 1,
    INCOMPLETE: 2,
    LEFTOVER: 3,
    CRASH: 4,
};

/** 每个码的一句话说明（给报告和文档用）。 */
const EXIT_MEANING = {
    0: '全部通过',
    1: '有真失败（真回归）—— 必须查',
    2: '本轮没跑完（环境/引擎问题）—— 可重试，不是回归',
    3: '有残留（文件留在用户工程里）—— 要人工清理',
    4: '测试自身中断 —— 脚本坏了',
};

module.exports = { EXIT, EXIT_MEANING };
